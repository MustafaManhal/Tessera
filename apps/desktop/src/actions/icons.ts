const BY_GROUP: Record<ActionGroup, LucideIcon> = {
  tabs: Icons.PanelTop,
  panes: Icons.LayoutPanelLeft,
  terminal: Icons.Terminal,
  projects: Icons.Folder,
  view: Icons.Eye,
};

/** Families of generated ids (tab.goTo1 to tab.goTo8, pane.focusLeft, pane.resizeUp, …) share one icon each. */
const BY_PREFIX: [string, LucideIcon][] = [
  ["tab.goTo", Icons.Hash],
  ["pane.focus", Icons.Focus],
  ["pane.resize", Icons.MoveHorizontal],
];

export function actionIcon(id: string, group: ActionGroup): LucideIcon {
  return BY_ID[id] ?? BY_PREFIX.find(([prefix]) => id.startsWith(prefix))?.[1] ?? BY_GROUP[group];
}
