export type StringKey = keyof typeof strings;

/**
 * Looks up a catalog string and fills `{name}` placeholders from `vars`. A placeholder without a value stays as
 * written, so a library that fills its own placeholders (Radix's `{hotkey}`) still can.
 */
export function t(key: StringKey, vars?: Readonly<Record<string, string | number>>): string {
  const text: string = strings[key];
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}
